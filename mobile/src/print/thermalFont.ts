const CELL = 8;

/** Rupee sign has no thermal glyph. "Rs." stays readable on the sticker. */
export function thermalPlain(text: string): string {
  return String(text ?? '')
    .replace(/₹/g, 'Rs.')
    .replace(/[–—]/g, '-')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[^\x20-\x7E]/g, '');
}

export function thermalAdvance(scaleX: number, gap = 2): number {
  return CELL * scaleX + gap;
}

export function thermalWidth(text: string, scaleX: number, gap = 2): number {
  const value = thermalPlain(text);
  if (!value) return 0;
  return value.length * thermalAdvance(scaleX, gap) - gap;
}

export function thermalHeight(scaleY: number): number {
  return CELL * scaleY;
}

export function clipThermal(text: string, maxWidth: number, scaleX: number, gap = 2): string {
  const value = thermalPlain(text);
  if (maxWidth <= 0) return '';
  if (thermalWidth(value, scaleX, gap) <= maxWidth) return value;
  const ellipsis = '..';
  let end = value.length;
  while (end > 0 && thermalWidth(`${value.slice(0, end)}${ellipsis}`, scaleX, gap) > maxWidth) {
    end -= 1;
  }
  return end <= 0 ? ellipsis : `${value.slice(0, end)}${ellipsis}`;
}

/** Draw one line. (x, y) is the top-left of the first glyph. */
export function drawThermalText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scaleX: number,
  scaleY: number,
  gap = 2,
): void {
  const value = thermalPlain(text);
  if (!value) return;
  let cursor = Math.round(x);
  const top = Math.round(y);
  ctx.fillStyle = '#000';
  for (let i = 0; i < value.length; i += 1) {
    const rows = ROWS[value[i]] || ROWS['?'];
    for (let row = 0; row < CELL; row += 1) {
      const bits = rows[row] || 0;
      for (let col = 0; col < CELL; col += 1) {
        if ((bits & (0x80 >> col)) === 0) continue;
        ctx.fillRect(cursor + col * scaleX, top + row * scaleY, scaleX, scaleY);
      }
    }
    cursor += CELL * scaleX + gap;
  }
}
