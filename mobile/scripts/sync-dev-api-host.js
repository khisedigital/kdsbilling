#!/usr/bin/env node
/**
 * Writes the developer machine's LAN IP for physical-device testing.
 * Run automatically before start / run-android / run-ios.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');

function pickLanIp() {
  const nets = os.networkInterfaces();
  const candidates = [];

  for (const entries of Object.values(nets)) {
    if (!entries) continue;
    for (const net of entries) {
      if (net.family !== 'IPv4' || net.internal) continue;
      candidates.push(net.address);
    }
  }

  // Prefer common Wi-Fi / Ethernet interface ranges over link-local or docker bridges
  const preferred = candidates.find(
    (ip) => ip.startsWith('192.168.') || ip.startsWith('10.') || /^172\.(1[6-9]|2\d|3[01])\./.test(ip)
  );

  return preferred || candidates[0] || '127.0.0.1';
}

const ip = pickLanIp();
const outPath = path.join(__dirname, '../src/config/dev-host.generated.ts');
const contents = `/** Auto-generated by scripts/sync-dev-api-host.js — do not edit */\nexport const DEV_MACHINE_LAN_IP = '${ip}';\n`;

fs.writeFileSync(outPath, contents, 'utf8');
console.log(`[sync-dev-api-host] Using LAN IP ${ip} for physical device API`);
